const BADashboard: React.FC = () => {
  const { t } = useTranslation();
  const { auth } = useStores();
  const isAdmin = auth.user?.isAdmin ?? false;
  const [isGithubOpen, setIsGithubOpen] = useState(false);

  return (
    <DashboardContainer>
      <MainContent>
        <ContentArea>
          <DashboardHeader>
            <HeaderTitle>{t("BA Dashboard")}</HeaderTitle>
            <HeaderSubtitle>
              {t("Monitor sync status, review gap findings from pull requests generated by agents, and consider proposals to address them.")}
            </HeaderSubtitle>
          </DashboardHeader>
          <StatsCards />
          <BottomSection>
            <PendingApprovals />
            <RightColumn>
              <RecentActivity />
            </RightColumn>
          </BottomSection>
        </ContentArea>
      </MainContent>

      {/* Floating GitHub Button - only visible for admins */}
      {isAdmin && (
        <FloatingGithubButton
          onClick={() => setIsGithubOpen(true)}
          title={t("Github Configuration")}
        >
          <GithubIcon />
        </FloatingGithubButton>
      )}

      {/* GitHub Configuration Modal */}
      {isAdmin && isGithubOpen && (
        <ModalOverlay onClick={() => setIsGithubOpen(false)}>
          <ModalContent onClick={(e) => e.stopPropagation()}>
            <ModalCloseButton onClick={() => setIsGithubOpen(false)}>
              ✕
            </ModalCloseButton>
            <ModalBody>
              <Suspense fallback={<ModalLoading>{t("Loading...")}</ModalLoading>}>
                <GithubConfig configOnly />
              </Suspense>
            </ModalBody>
          </ModalContent>
        </ModalOverlay>
      )}
    </DashboardContainer>
  );
};

